def run(module: str, root: Path) -> bool:
    r = subprocess.run([sys.executable, "-m", "unittest", module, "-q"], cwd=root,
                       capture_output=True, text=True)
    return r.returncode == 0


def main() -> int:
    survivors = 0
    for desc, rel, find, replace, module in MUTANTS:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp) / "repo"
            # Gitignored local data (photos, review output, the virtualenv) isn't needed and is large.
            shutil.copytree(REPO, root, ignore=shutil.ignore_patterns(".git", "__pycache__", ".venv", ".commerce-os",
                                                                      "raw", "node_modules"))
            target = root / rel
            text = target.read_text(encoding="utf-8")
            if find not in text:
                print(f"✗ STALE  {desc}: pattern not found in {rel}")
                survivors += 1
                continue
            target.write_text(text.replace(find, replace, 1), encoding="utf-8")
            if run(module, root):
                print(f"✗ SURVIVED  {desc} ({module} still passes)")
                survivors += 1
            else:
                print(f"✓ caught  {desc}")
    print(f"\n{len(MUTANTS) - survivors}/{len(MUTANTS)} mutants caught")
    return 1 if survivors else 0


if __name__ == "__main__":
    sys.exit(main())
